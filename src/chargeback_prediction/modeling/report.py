"""Render a :class:`BaselineReport` as Markdown, JSON and a calibration / PR-curve figure."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import joblib
import matplotlib

matplotlib.use("Agg")  # headless: CI and servers have no display

import matplotlib.pyplot as plt
import numpy as np

from chargeback_prediction.modeling.train import BaselineReport


def _pct(x: float) -> str:
    return f"{x:.1%}"


def render_markdown(report: BaselineReport, *, figure: str | None = None) -> str:
    """Human-readable summary: split, headline metrics, precision@k and calibration."""
    s, base = report.split, report.test_base_rate
    lines = [
        "# Baseline model report",
        "",
        "<!-- Generated by `cbp train`. Synthetic data only. -->",
        "",
        "## Split",
        "",
        "| Window | Rows | Disputes | Rate | `created_at` range |",
        "|---|---|---|---|---|",
        f"| train | {len(s.train):,} | {int(s.train.y.sum()):,} | {_pct(s.train.positive_rate)} "
        f"| {s.train.created_at[0]:%Y-%m-%d} → {s.train.created_at[-1]:%Y-%m-%d} |",
        f"| test | {len(s.test):,} | {int(s.test.y.sum()):,} | {_pct(base)} "
        f"| {s.test.created_at[0]:%Y-%m-%d} → {s.test.created_at[-1]:%Y-%m-%d} |",
        "",
        f"Label gap: {report.config.label_gap_days} days "
        f"({s.dropped_in_gap:,} rows dropped between train end and test start); "
        f"{s.dropped_immature:,} rows with an open dispute window excluded.",
        "",
        "## Headline metrics (test window)",
        "",
        "| Model | PR-AUC | Lift vs. base rate | Brier | ECE | Fit time |",
        "|---|---|---|---|---|---|",
    ]
    for ev in report.evaluations:
        lines.append(
            f"| {ev.kind.label} | {ev.pr_auc:.3f} | {ev.pr_auc / base:.1f}× | "
            f"{ev.brier:.4f} | {ev.ece:.4f} | {ev.fit_seconds:.2f}s |"
        )
    lines += [
        f"| *Random scorer* | {base:.3f} | 1.0× | {base * (1 - base):.4f} | — | — |",
        "",
        "## Precision@k (review budget as share of test traffic)",
        "",
        "| Model | "
        + " | ".join(f"top {_pct(a.budget)} (k={a.k:,})" for a in report.evaluations[0].at_k)
        + " |",
        "|---|" + "---|" * len(report.evaluations[0].at_k),
    ]
    for ev in report.evaluations:
        cells = [
            f"P {_pct(a.precision)} · R {_pct(a.recall)} · {a.lift(base):.0f}×" for a in ev.at_k
        ]
        lines.append(f"| {ev.kind.label} | " + " | ".join(cells) + " |")
    lines += [
        "",
        "P = precision, R = share of all test disputes caught, × = lift over random review.",
        "",
        "## Calibration (quantile bins)",
        "",
    ]
    for ev in report.evaluations:
        lines += [
            f"**{ev.kind.label}**",
            "",
            "| Bin | Rows | Mean predicted | Observed rate |",
            "|---|---|---|---|",
        ]
        lines += [
            f"| {i} | {b.count:,} | {_pct(b.mean_predicted)} | {_pct(b.observed_rate)} |"
            for i, b in enumerate(ev.calibration, start=1)
        ]
        lines.append("")
    if figure:
        lines += [f"![Calibration and precision-recall curves]({figure})", ""]
    return "\n".join(lines)


def report_to_dict(report: BaselineReport) -> dict[str, Any]:
    """Machine-readable metrics (no scores or models), for CI checks and dashboards."""
    s = report.split
    return {
        "split": {
            "train_rows": len(s.train),
            "train_disputes": int(s.train.y.sum()),
            "test_rows": len(s.test),
            "test_disputes": int(s.test.y.sum()),
            "train_end": s.train_end.isoformat(),
            "cutoff": s.cutoff.isoformat(),
            "label_gap_days": report.config.label_gap_days,
            "dropped_in_gap": s.dropped_in_gap,
            "dropped_immature": s.dropped_immature,
        },
        "test_base_rate": report.test_base_rate,
        "models": {
            ev.kind.value: {
                "pr_auc": ev.pr_auc,
                "brier": ev.brier,
                "ece": ev.ece,
                "at_k": [
                    {"budget": a.budget, "k": a.k, "precision": a.precision, "recall": a.recall}
                    for a in ev.at_k
                ],
                "calibration": [
                    {
                        "count": b.count,
                        "mean_predicted": b.mean_predicted,
                        "observed_rate": b.observed_rate,
                    }
                    for b in ev.calibration
                ],
            }
            for ev in report.evaluations
        },
    }


def _pr_curve(y: np.ndarray[Any, Any], scores: np.ndarray[Any, Any]) -> tuple[Any, Any]:
    order = np.argsort(-scores, kind="mergesort")
    tp = np.cumsum(y[order])
    precision = tp / np.arange(1, len(y) + 1)
    recall = tp / max(int(y.sum()), 1)
    return recall, precision


def plot_report(report: BaselineReport, path: Path) -> Path:
    """Two panels: reliability diagram (log-log, quantile bins) and precision-recall curves."""
    path.parent.mkdir(parents=True, exist_ok=True)
    fig, (ax_cal, ax_pr) = plt.subplots(1, 2, figsize=(11, 4.5), constrained_layout=True)
    y = report.split.test.y
    base = report.test_base_rate

    lo = min(
        min(b.mean_predicted for b in ev.calibration if b.mean_predicted > 0)
        for ev in report.evaluations
    )
    lo = max(lo / 2, 1e-4)
    ax_cal.plot([lo, 1], [lo, 1], ls="--", color="grey", lw=1, label="perfect")
    for ev in report.evaluations:
        xs = [b.mean_predicted for b in ev.calibration]
        ys = [max(b.observed_rate, lo) for b in ev.calibration]  # 0 observed → floor for log
        ax_cal.plot(xs, ys, marker="o", label=f"{ev.kind.label} (ECE {ev.ece:.3f})")
    ax_cal.set(
        xscale="log",
        yscale="log",
        xlim=(lo, 1),
        ylim=(lo, 1),
        xlabel="mean predicted dispute probability",
        ylabel="observed dispute rate",
        title="Calibration (test window, quantile bins)",
    )
    ax_cal.legend(loc="upper left", fontsize=8)

    for ev in report.evaluations:
        recall, precision = _pr_curve(y, ev.scores)
        ax_pr.plot(recall, precision, label=f"{ev.kind.label} (PR-AUC {ev.pr_auc:.3f})")
    ax_pr.axhline(base, ls="--", color="grey", lw=1, label=f"random ({base:.3f})")
    ax_pr.set(
        xlim=(0, 1),
        ylim=(0, 1.02),
        xlabel="recall (share of disputes caught)",
        ylabel="precision",
        title="Precision-recall (test window)",
    )
    ax_pr.legend(loc="upper right", fontsize=8)
    fig.savefig(path, dpi=120)
    plt.close(fig)
    return path


def write_artifacts(report: BaselineReport, out_dir: Path) -> dict[str, Path]:
    """Write models (joblib), metrics.json, report.md and calibration.png under ``out_dir``."""
    out_dir.mkdir(parents=True, exist_ok=True)
    paths: dict[str, Path] = {}
    for kind, model in report.models.items():
        model_path = out_dir / f"model_{kind.value}.joblib"
        joblib.dump(model, model_path)
        paths[f"model_{kind.value}"] = model_path
    paths["figure"] = plot_report(report, out_dir / "calibration.png")
    metrics_path = out_dir / "metrics.json"
    metrics_path.write_text(json.dumps(report_to_dict(report), indent=2) + "\n", encoding="utf-8")
    paths["metrics"] = metrics_path
    report_path = out_dir / "report.md"
    report_path.write_text(render_markdown(report, figure="calibration.png"), encoding="utf-8")
    paths["report"] = report_path
    return paths
