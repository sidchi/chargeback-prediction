"""Render an :class:`EvaluationReport`: cost report, model card, cost-curve figure and JSON."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import matplotlib

matplotlib.use("Agg")  # headless: CI and servers have no display

import matplotlib.pyplot as plt
import numpy as np
from matplotlib.ticker import NullLocator

from chargeback_prediction import __version__
from chargeback_prediction.evaluation.bootstrap import Interval
from chargeback_prediction.evaluation.costs import PolicyKind, PolicyOutcome
from chargeback_prediction.evaluation.run import EvaluationReport, ModelCostEvaluation

_GENERATED = "<!-- Generated by `cbp evaluate`. Synthetic data only; do not edit by hand. -->"


def _usd(x: float) -> str:
    return f"−${-x:,.0f}" if x < 0 else f"${x:,.0f}"


def _pct(x: float) -> str:
    return f"{x:.1%}"


def _policy_row(name: str, o: PolicyOutcome, base: PolicyOutcome) -> str:
    return (
        f"| {name} | {o.blocked:,} ({_pct(o.block_rate)}) "
        f"| {o.disputes_blocked:,} / {o.disputes:,} "
        f"| {o.false_declines:,} | {_usd(o.chargeback_cost)} | {_usd(o.false_decline_cost)} "
        f"| {_usd(o.total_cost)} | {_usd(o.cost_per_1k)} | {_usd(o.savings_vs(base))} "
        f"| {_pct(o.residual_dispute_ratio)} |"
    )


_POLICY_HEADER = [
    "| Policy | Blocked | Disputes blocked | False declines | Chargeback cost "
    "| False-decline cost | Total | Per 1k charges | Saved vs. approve-all "
    "| Residual dispute ratio |",
    "|---|---|---|---|---|---|---|---|---|---|",
]


def _cost_assumptions(report: EvaluationReport) -> list[str]:
    c = report.config.costs
    return [
        "| Assumption | Value |",
        "|---|---|",
        f"| Network dispute fee | ${c.dispute_fee_usd:,.2f} per chargeback |",
        f"| Ops handling | ${c.ops_cost_per_dispute_usd:,.2f} per chargeback |",
        f"| Representment recovery | {_pct(c.representment_recovery_rate)} of disputed amount |",
        f"| Gross margin lost on a false decline | {_pct(c.gross_margin)} of amount |",
        f"| Churn after a false decline | {_pct(c.false_decline_churn_rate)} × "
        f"${c.customer_lifetime_value_usd:,.0f} lifetime value |",
        f"| Cost of acting on a flag | ${c.action_cost_usd:,.2f} per blocked charge |",
        "",
        "So a typical charge of "
        f"${float(np.median(report.amounts)):,.2f} costs "
        f"{_usd(float(c.chargeback_cost(np.median(report.amounts))))} if it becomes a chargeback "
        f"and {_usd(float(c.false_decline_cost(np.median(report.amounts))))} if it is falsely "
        "declined; blocking pays off above a dispute probability of "
        f"{_pct(float(c.break_even_probability(np.median(report.amounts))))}.",
    ]


def render_cost_report(report: EvaluationReport, *, figure: str | None = None) -> str:
    """Cost-weighted evaluation: policies, intervals, model comparison and sensitivity."""
    base, perfect = report.approve_all, report.perfect
    cfg = report.config
    level = f"{cfg.level:.0%}"
    test = report.baseline.split.test
    lines = [
        "# Cost-weighted evaluation",
        "",
        _GENERATED,
        "",
        f"Test window: {len(test):,} charges, {base.disputes:,} disputes "
        f"({_pct(report.baseline.test_base_rate)}), "
        f"{test.created_at[0]:%Y-%m-%d} → {test.created_at[-1]:%Y-%m-%d}. "
        f"Intervals are {level} stratified bootstrap ({cfg.n_resamples:,} resamples).",
        "",
        "## Cost assumptions",
        "",
        *_cost_assumptions(report),
        "",
        "## Headline",
        "",
        f"| Model | PR-AUC ({level} CI) | Expected-cost rule saves per 1k charges ({level} CI) "
        "| Share of achievable saving |",
        "|---|---|---|---|",
    ]
    for m in report.models:
        lines.append(
            f"| {m.kind.label} | {m.pr_auc.format()} | "
            f"{_usd(m.savings_per_1k.estimate)} [{_usd(m.savings_per_1k.low)}, "
            f"{_usd(m.savings_per_1k.high)}] | {_pct(m.capture_of_achievable(base, perfect))} |"
        )
    lines += [
        "",
        f"Approving everything costs {_usd(base.cost_per_1k)} per 1,000 charges; perfect "
        f"foresight would cost {_usd(perfect.cost_per_1k)}. The share of achievable saving is "
        "how much of that gap the model's expected-cost rule closes.",
        "",
    ]
    if report.comparisons:
        lines += ["## Model comparison (paired bootstrap)", ""]
        for c in report.comparisons:
            d, s = c.pr_auc_difference, c.savings_difference_per_1k
            verdict = (
                "the difference is unlikely to be resampling noise"
                if d.excludes_zero()
                else "the interval includes zero, so the test window cannot separate them"
            )
            lines += [
                f"- **{c.better.label} − {c.worse.label}**: PR-AUC {d.format('+.3f')}; "
                f"saving per 1k charges {_usd(s.estimate)} [{_usd(s.low)}, {_usd(s.high)}]. "
                f"For PR-AUC {verdict}.",
            ]
        lines.append("")
    for m in report.models:
        lines += [
            f"## {m.kind.label}: blocking policies",
            "",
            *_POLICY_HEADER,
            _policy_row(PolicyKind.APPROVE_ALL.label, base, base),
            _policy_row(PolicyKind.EXPECTED_COST.label, m.policies[PolicyKind.EXPECTED_COST], base),
            _policy_row(
                f"{PolicyKind.REVIEW_BUDGET.label}, {_pct(cfg.review_budget)} of traffic",
                m.policies[PolicyKind.REVIEW_BUDGET],
                base,
            ),
            _policy_row(
                f"{PolicyKind.HINDSIGHT_THRESHOLD.label} (p ≥ {m.hindsight_threshold:.3f})",
                m.policies[PolicyKind.HINDSIGHT_THRESHOLD],
                base,
            ),
            _policy_row(PolicyKind.PERFECT_FORESIGHT.label, perfect, base),
            "",
        ]
        if m.categories:
            lines += [
                "Disputes blocked by the expected-cost rule, by category:",
                "",
                "| Category | Disputes | Blocked | Share |",
                "|---|---|---|---|",
                *(
                    f"| {c.category} | {c.disputes:,} | {c.blocked:,} | {_pct(c.rate)} |"
                    for c in m.categories
                ),
                "",
            ]
        lines += [
            "Sensitivity of the expected-cost rule to the false-decline cost "
            "(margin and lifetime value scaled together):",
            "",
            "| False-decline cost | Blocked | Disputes blocked | False declines "
            "| Saved per 1k charges |",
            "|---|---|---|---|---|",
            *(
                f"| ×{r.false_decline_multiplier:g} | {r.outcome.blocked:,} "
                f"| {r.outcome.disputes_blocked:,} | {r.outcome.false_declines:,} "
                f"| {_usd(r.savings_per_1k)} |"
                for r in m.sensitivity
            ),
            "",
        ]
    if figure:
        lines += [f"![Cost curves and sensitivity]({figure})", ""]
    return "\n".join(lines)


def _weakest_bin_note(m: ModelCostEvaluation) -> list[str]:
    """Flag the lowest-score bin when it under-predicts: disputes that look entirely normal."""
    if not m.ranking.calibration:
        return []
    low = m.ranking.calibration[0]
    if low.observed_rate <= 2 * low.mean_predicted:
        return []
    return [
        "- **Where it is weakest:** charges that look entirely normal. The lowest-scored "
        f"bin has an observed dispute rate of {_pct(low.observed_rate)} against "
        f"{_pct(low.mean_predicted)} predicted; no behavioural feature separates them.",
    ]


def render_model_card(report: EvaluationReport) -> str:
    """A model card (Mitchell et al., 2019) for the recommended model, filled from the report."""
    m = report.recommended()
    base, perfect = report.approve_all, report.perfect
    s = report.baseline.split
    ev = m.ranking
    level = f"{report.config.level:.0%}"
    rule = m.expected_cost
    others = [o for o in report.models if o.kind is not m.kind]
    lines = [
        f"# Model card: chargeback risk — {m.kind.label.lower()}",
        "",
        _GENERATED,
        "",
        "## Model details",
        "",
        f"- **Model:** {m.kind.label} (`{m.kind.value}`), chargeback-prediction v{__version__}.",
        f"- **Output:** calibrated probability that a card-not-present charge is disputed within "
        f"the network dispute window; {len(s.test.feature_names)} point-in-time features "
        "(see [features.md](../features.md)).",
        "- **Selection:** lowest test-window cost under the expected-cost blocking rule"
        + (f", ahead of {', '.join(o.kind.label.lower() for o in others)}." if others else "."),
        "- **Explanations:** exact SHAP values per prediction, served by `/v1/explain`.",
        "- **License:** MIT. **Contact:** repository issues.",
        "",
        "## Intended use",
        "",
        "- Rank recurring and one-off card-not-present charges by dispute risk **before** "
        "they are submitted, so a merchant can skip, step-up, remind or review the riskiest.",
        "- Feed the per-amount expected-cost rule, which needs calibrated probabilities.",
        "- Prioritise representment effort and evidence gathering once a dispute lands.",
        "",
        "**Out of scope:** authorisation-time fraud decisions for card-present traffic; credit "
        "or eligibility decisions about people; use on real data without retraining and "
        "re-evaluation; any automated action without a human-reviewable reason (the SHAP "
        "factors and rationale exist for that).",
        "",
        "## Training and evaluation data",
        "",
        "Fully **synthetic** customers, subscriptions, charges and disputes from this "
        "repository's generator, with planted friendly-fraud and stolen-card patterns. No real "
        "cardholder or merchant data was used.",
        "",
        "| Window | Charges | Disputes | Rate | Dates |",
        "|---|---|---|---|---|",
        f"| train | {len(s.train):,} | {int(s.train.y.sum()):,} | {_pct(s.train.positive_rate)} "
        f"| {s.train.created_at[0]:%Y-%m-%d} → {s.train.created_at[-1]:%Y-%m-%d} |",
        f"| test | {len(s.test):,} | {int(s.test.y.sum()):,} | {_pct(s.test.positive_rate)} "
        f"| {s.test.created_at[0]:%Y-%m-%d} → {s.test.created_at[-1]:%Y-%m-%d} |",
        "",
        f"Time-based split with a {report.baseline.config.label_gap_days}-day label gap, so every "
        "training label was final before the first test charge.",
        "",
        "## Metrics (test window)",
        "",
        f"| Metric | Value ({level} CI where shown) |",
        "|---|---|",
        f"| PR-AUC | {m.pr_auc.format()} (random: {report.baseline.test_base_rate:.3f}) |",
        *(
            f"| Precision / recall at top {_pct(a.budget)} | {_pct(a.precision)} / "
            f"{_pct(a.recall)} |"
            for a in ev.at_k
        ),
        f"| Brier score | {ev.brier:.4f} |",
        f"| Expected calibration error | {ev.ece:.4f} |",
        f"| Saved per 1k charges (expected-cost rule) | {_usd(m.savings_per_1k.estimate)} "
        f"[{_usd(m.savings_per_1k.low)}, {_usd(m.savings_per_1k.high)}] |",
        f"| Share of achievable saving | {_pct(m.capture_of_achievable(base, perfect))} |",
        f"| Charges blocked | {rule.blocked:,} ({_pct(rule.block_rate)}), of which "
        f"{rule.false_declines:,} false declines |",
        f"| Residual dispute ratio | {_pct(rule.residual_dispute_ratio)} "
        f"(approve-all: {_pct(base.residual_dispute_ratio)}) |",
        "",
        "Full tables, the cost assumptions and the sensitivity analysis are in "
        "[the cost report](report.md).",
        "",
        "## Limitations",
        "",
        "- **Synthetic data.** The planted signals are cleaner and more monotone than real "
        "traffic; absolute numbers say nothing about production performance.",
        "- **Few positives.** The test window holds only "
        f"{base.disputes:,} disputes; read the intervals, not the point estimates.",
        "- **Label delay.** Disputes arrive weeks to months after the charge, so live "
        "monitoring of precision lags by the dispute window; track score distribution drift and "
        "calibration on matured cohorts instead.",
        *_weakest_bin_note(m),
        "- **Costs are assumptions.** The expected-cost rule is only as good as the unit "
        "economics fed to it; the sensitivity table shows how the decision shifts.",
        "",
        "## Ethical considerations",
        "",
        "- **False declines land on legitimate customers.** Prefer soft actions (reminders, "
        "step-up) over hard declines, and keep a human-reviewable reason for every block.",
        "- **Proxy features.** No protected attributes are used, but geography (IP/BIN country "
        "mismatch) and email domain can correlate with them. Before production use, audit "
        "block and false-decline rates across regions and customer segments.",
        "- **Friendly-fraud labels are contested.** A 'consumer' dispute may reflect a genuinely "
        "confusing descriptor or cancellation flow; the right fix is often product-side, not "
        "a block.",
        "",
        "## Maintenance",
        "",
        "Retrain on a rolling window once new labels mature; re-run `cbp evaluate` to refresh "
        "this card and check calibration before changing any blocking threshold.",
        "",
    ]
    return "\n".join(lines)


def report_to_dict(report: EvaluationReport) -> dict[str, Any]:
    """Machine-readable summary for dashboards and CI checks."""

    def outcome(o: PolicyOutcome) -> dict[str, Any]:
        return {
            "blocked": o.blocked,
            "disputes_blocked": o.disputes_blocked,
            "false_declines": o.false_declines,
            "total_cost": o.total_cost,
            "cost_per_1k": o.cost_per_1k,
            "savings_vs_approve_all": o.savings_vs(report.approve_all),
            "residual_dispute_ratio": o.residual_dispute_ratio,
        }

    def interval(i: Interval) -> dict[str, float]:
        return {"estimate": i.estimate, "low": i.low, "high": i.high, "level": i.level}

    return {
        "test_rows": report.approve_all.n,
        "test_disputes": report.approve_all.disputes,
        "cost_model": {
            name: getattr(report.config.costs, name)
            for name in report.config.costs.__dataclass_fields__
        },
        "approve_all": outcome(report.approve_all),
        "perfect_foresight": outcome(report.perfect),
        "recommended": report.recommended().kind.value,
        "models": {
            m.kind.value: {
                "pr_auc": interval(m.pr_auc),
                "savings_per_1k": interval(m.savings_per_1k),
                "hindsight_threshold": m.hindsight_threshold,
                "policies": {k.value: outcome(o) for k, o in m.policies.items()},
                "categories": {c.category: [c.blocked, c.disputes] for c in m.categories},
                "sensitivity": [
                    {"multiplier": r.false_decline_multiplier, "savings_per_1k": r.savings_per_1k}
                    for r in m.sensitivity
                ],
            }
            for m in report.models
        },
        "comparisons": [
            {
                "better": c.better.value,
                "worse": c.worse.value,
                "pr_auc_difference": interval(c.pr_auc_difference),
                "savings_difference_per_1k": interval(c.savings_difference_per_1k),
            }
            for c in report.comparisons
        ],
    }


def _plot_model_curve(ax: Any, m: ModelCostEvaluation, base_per_1k: float, n: int) -> None:
    share = m.curve.blocked[1:] / n
    saved = base_per_1k - 1_000 * m.curve.total_cost[1:] / n
    (line,) = ax.plot(share, saved, label=m.kind.label)
    rule = m.expected_cost
    ax.plot(
        max(rule.block_rate, 1 / n),
        base_per_1k - rule.cost_per_1k,
        marker="o",
        color=line.get_color(),
        ls="none",
        label=f"{m.kind.label}: expected-cost rule",
    )


def plot_costs(report: EvaluationReport, path: Path) -> Path:
    """Left: saving vs. share of traffic blocked. Right: saving vs. false-decline cost."""
    path.parent.mkdir(parents=True, exist_ok=True)
    n = report.approve_all.n
    base_per_1k = report.approve_all.cost_per_1k
    fig, (ax_curve, ax_sens) = plt.subplots(1, 2, figsize=(11, 4.5), constrained_layout=True)
    for m in report.models:
        _plot_model_curve(ax_curve, m, base_per_1k, n)
    ceiling = base_per_1k - report.perfect.cost_per_1k
    ax_curve.axhline(0, color="grey", lw=1, ls="--", label="approve everything")
    ax_curve.axhline(ceiling, color="grey", lw=1, ls=":", label="perfect foresight")
    ax_curve.set(
        xscale="log",
        xlim=(1 / n, 0.2),
        ylim=(-0.5 * ceiling, 1.05 * ceiling),
        xlabel="share of charges blocked (highest score first)",
        ylabel="saved per 1,000 charges vs. approve-all ($)",
        title="Blocking the top-k charges (test window)",
    )
    ax_curve.legend(fontsize=8, loc="upper left", bbox_to_anchor=(0.0, 0.94))

    multipliers = [r.false_decline_multiplier for r in report.models[0].sensitivity]
    for m in report.models:
        ax_sens.plot(
            [r.false_decline_multiplier for r in m.sensitivity],
            [r.savings_per_1k for r in m.sensitivity],
            marker="o",
            label=m.kind.label,
        )
    ax_sens.axhline(0, color="grey", lw=1)
    ax_sens.set(
        xscale="log",
        xlabel="false-decline cost multiplier",
        ylabel="saved per 1,000 charges ($)",
        title="Expected-cost rule: sensitivity to false-decline cost",
    )
    ax_sens.xaxis.set_minor_locator(NullLocator())
    ax_sens.set_xticks(multipliers, [f"×{x:g}" for x in multipliers])
    ax_sens.legend(fontsize=8)
    fig.savefig(path, dpi=120)
    plt.close(fig)
    return path


def write_artifacts(report: EvaluationReport, out_dir: Path) -> dict[str, Path]:
    """Write report.md, model_card.md, cost_curve.png and evaluation.json under ``out_dir``."""
    out_dir.mkdir(parents=True, exist_ok=True)
    paths = {"figure": plot_costs(report, out_dir / "cost_curve.png")}
    paths["report"] = out_dir / "report.md"
    paths["report"].write_text(
        render_cost_report(report, figure="cost_curve.png"), encoding="utf-8"
    )
    paths["model_card"] = out_dir / "model_card.md"
    paths["model_card"].write_text(render_model_card(report), encoding="utf-8")
    paths["metrics"] = out_dir / "evaluation.json"
    paths["metrics"].write_text(
        json.dumps(report_to_dict(report), indent=2) + "\n", encoding="utf-8"
    )
    return paths
