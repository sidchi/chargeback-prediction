"""Render a :class:`MonitorReport` as Markdown and JSON."""

from __future__ import annotations

import json
import math
from pathlib import Path
from typing import Any

from chargeback_prediction.modeling import ModelKind
from chargeback_prediction.monitoring.monitor import (
    CalibrationCheck,
    MonitorReport,
    Status,
    WindowReport,
)

_BADGE = {
    Status.OK: "ok",
    Status.WARN: "**warn**",
    Status.ALERT: "**ALERT**",
    Status.PENDING: "pending",
}


def _window_label(w: WindowReport) -> str:
    return f"{w.start:%Y-%m-%d} → {w.end:%m-%d}"


def _calibration_cells(c: CalibrationCheck | None) -> tuple[str, str]:
    if c is None:
        return "—", "—"
    return f"{c.observed} / {c.expected:.1f}", f"{c.z:+.1f}"


def render_markdown(report: MonitorReport, kind: ModelKind) -> str:
    cfg = report.config
    lines = [
        "# Model monitoring report",
        "",
        "<!-- Generated by `cbp monitor`. Synthetic data only. -->",
        "",
        f"**Model:** {kind.label} · **trained on data up to** {report.reference_end:%Y-%m-%d} · "
        f"**monitored from** {report.monitored_from:%Y-%m-%d} in {cfg.window_days}-day windows",
        "",
        f"**Reference (training window):** {report.reference_start:%Y-%m-%d} → "
        f"{report.reference_end:%Y-%m-%d}, {report.reference_rows:,} charges, mean score "
        f"{report.reference_mean_score:.2%}, observed dispute rate "
        f"{report.reference_dispute_rate:.2%}",
        "",
        f"**Verdict: {report.status.label.upper()}** (drift {report.drift_status.label}, "
        f"calibration {report.calibration_status.label}). {report.headline()}",
        "",
        "## Windows",
        "",
        "| Window | Charges | Mean score | Score PSI | Labels matured | Disputes obs. / exp. | z "
        "| Drift | Calibration |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for w in report.windows:
        obs_exp, z = _calibration_cells(w.calibration)
        lines.append(
            f"| {_window_label(w)} | {w.rows:,} | {w.mean_score:.2%} | {w.score_psi:.3f} "
            f"| {w.label_coverage:.0%} | {obs_exp} | {z} | {_BADGE[w.drift_status]} "
            f"| {_BADGE[w.calibration_status]} |"
        )
    lines += [
        "",
        f"Score PSI thresholds: warn ≥ {cfg.psi_warn}, alert ≥ {cfg.psi_alert}. Sampling noise "
        "alone gives a PSI of about "
        f"{min(w.noise_floor for w in report.windows):.3f}–"
        f"{max(w.noise_floor for w in report.windows):.3f} at these window sizes. "
        f"Calibration: z-test of observed vs. expected disputes on matured rows only "
        f"(warn |z| ≥ {cfg.z_warn}, alert |z| ≥ {cfg.z_alert}; needs ≥ "
        f"{cfg.min_labeled_rows:,} matured rows).",
        "",
    ]

    drifted = sorted(
        {d.feature for w in report.windows for d in w.drifted_features(cfg.top_features)}
    )
    lines += ["## Feature drift", ""]
    if not drifted:
        lines += ["No feature reached the warning threshold in any window.", ""]
    else:
        lines += [
            f"PSI per window for every feature that ranked in a window's top {cfg.top_features} "
            f"and crossed {cfg.psi_warn}; the mean columns compare the training window with "
            "the last window.",
            "",
            "| Feature | "
            + " | ".join(f"{w.start:%m-%d}" for w in report.windows)
            + " | Train mean | Last mean |",
            "|---|" + "---|" * (len(report.windows) + 2),
        ]
        last = report.windows[-1]
        for name in sorted(
            drifted,
            key=lambda f: -max(d.psi for w in report.windows for d in w.features if d.feature == f),
        ):
            by_window = [next(d for d in w.features if d.feature == name) for w in report.windows]
            last_d = next(d for d in last.features if d.feature == name)
            lines.append(
                f"| `{name}` | "
                + " | ".join(f"{d.psi:.2f}" for d in by_window)
                + f" | {last_d.reference_mean:,.2f} | {last_d.current_mean:,.2f} |"
            )
        lines.append("")

    flagged = [w for w in report.windows if w.reasons]
    if flagged:
        lines += ["## Why each window was flagged", ""]
        for w in flagged:
            lines.append(f"- **{_window_label(w)}**: " + "; ".join(w.reasons))
        lines.append("")
    return "\n".join(lines)


def _finite(x: float) -> float | None:
    return x if math.isfinite(x) else None


def to_json(report: MonitorReport, kind: ModelKind) -> dict[str, Any]:
    cfg = report.config
    return {
        "model": kind.value,
        "status": report.status.label,
        "drift_status": report.drift_status.label,
        "calibration_status": report.calibration_status.label,
        "headline": report.headline(),
        "config": {
            "window_days": cfg.window_days,
            "psi_warn": cfg.psi_warn,
            "psi_alert": cfg.psi_alert,
            "z_warn": cfg.z_warn,
            "z_alert": cfg.z_alert,
            "min_window_rows": cfg.min_window_rows,
            "min_labeled_rows": cfg.min_labeled_rows,
            "n_bins": cfg.n_bins,
        },
        "reference": {
            "start": report.reference_start.isoformat(),
            "end": report.reference_end.isoformat(),
            "rows": report.reference_rows,
            "mean_score": report.reference_mean_score,
            "dispute_rate": report.reference_dispute_rate,
        },
        "monitored_from": report.monitored_from.isoformat(),
        "windows": [
            {
                "start": w.start.isoformat(),
                "end": w.end.isoformat(),
                "rows": w.rows,
                "mean_score": w.mean_score,
                "score_psi": w.score_psi,
                "noise_floor": w.noise_floor,
                "label_coverage": w.label_coverage,
                "status": w.status.label,
                "drift_status": w.drift_status.label,
                "calibration_status": w.calibration_status.label,
                "calibration": None
                if w.calibration is None
                else {
                    "rows": w.calibration.rows,
                    "observed": w.calibration.observed,
                    "expected": w.calibration.expected,
                    "ratio": _finite(w.calibration.ratio),
                    "z": w.calibration.z,
                },
                "features": {
                    d.feature: {
                        "psi": d.psi,
                        "reference_mean": d.reference_mean,
                        "current_mean": d.current_mean,
                        "status": d.status.label,
                    }
                    for d in w.features
                },
                "reasons": list(w.reasons),
            }
            for w in report.windows
        ],
    }


def write_artifacts(report: MonitorReport, kind: ModelKind, out_dir: Path) -> dict[str, Path]:
    """Write ``report.md`` and ``monitoring.json`` under ``out_dir``."""
    out_dir.mkdir(parents=True, exist_ok=True)
    paths = {"report": out_dir / "report.md", "metrics": out_dir / "monitoring.json"}
    paths["report"].write_text(render_markdown(report, kind) + "\n", encoding="utf-8")
    paths["metrics"].write_text(
        json.dumps(to_json(report, kind), indent=2) + "\n", encoding="utf-8"
    )
    return paths
